"""Render the cloud-init seed (user-data, network-config, meta-data) for a lab Pi.

The official Ubuntu Server image for the Raspberry Pi reads these files from its
boot partition on first boot. Values come from the environment (see flash.sh);
strings are emitted as JSON, which is valid YAML, so no value can break the
file's structure.

Usage: python3 dev/pi/render_seed.py <output dir>
"""

import json
import os
import sys
from pathlib import Path

REPO = "https://github.com/jorjazo/nocs"
HERE = Path(__file__).parent


def q(value: str) -> str:
    return json.dumps(value)


def write_file(path: str, content: str, permissions: str) -> list[str]:
    return [
        f"  - path: {q(path)}",
        f"    permissions: {q(permissions)}",
        f"    content: {q(content)}",
    ]


def user_data(env: dict[str, str]) -> str:
    """First boot only creates the user and installs a setup service.

    The actual installation (packages, Docker, uv, the repo, ASTAP) runs in
    nocs-lab-setup.service, which waits for the network and retries until it
    succeeds: cloud-init runs once, and a first boot without network (e.g. Wi-Fi
    still associating, clock not yet synced) would otherwise leave a bare system.
    """
    user = env["PI_USER"]
    settings = (
        f"PI_USER={user}\n"
        f"NOCS_REPO={REPO}\n"
        f"WITH_ASTAP={'1' if env.get('WITH_ASTAP', '1') == '1' else '0'}\n"
    )
    lines = [
        "#cloud-config",
        "# NOCS lab Pi: generated by dev/pi/render_seed.py",
        f"hostname: {q(env['PI_HOSTNAME'])}",
        "preserve_hostname: false",
        f"timezone: {q(env['PI_TIMEZONE'])}",
        "ssh_pwauth: false",
        "users:",
        f"  - name: {q(user)}",
        "    groups: [adm, sudo, video]",
        "    shell: /bin/bash",
        "    lock_passwd: true",
        '    sudo: "ALL=(ALL) NOPASSWD:ALL"',
        "    ssh_authorized_keys:",
        f"      - {q(env['PI_SSH_KEY'])}",
        "write_files:",
        *write_file("/etc/nocs-lab.env", settings, "0644"),
        *write_file(
            "/usr/local/sbin/nocs-lab-setup", (HERE / "nocs-lab-setup.sh").read_text(), "0755"
        ),
        *write_file(
            "/etc/systemd/system/nocs-lab-setup.service",
            (HERE / "nocs-lab-setup.service").read_text(),
            "0644",
        ),
        "runcmd:",
        '  - "systemctl daemon-reload"',
        '  - "systemctl enable nocs-lab-setup.service"',
        '  - "systemctl start --no-block nocs-lab-setup.service"',
        "",
    ]
    return "\n".join(lines)


def network_config(env: dict[str, str]) -> str:
    lines = [
        "network:",
        "  version: 2",
        "  ethernets:",
        "    eth0:",
        "      dhcp4: true",
        "      optional: true",
    ]
    if env.get("WIFI_SSID"):
        lines += [
            "  wifis:",
            "    wlan0:",
            "      dhcp4: true",
            "      optional: true",
            f"      regulatory-domain: {q(env.get('WIFI_COUNTRY', 'CL'))}",
            "      access-points:",
            f"        {q(env['WIFI_SSID'])}:",
            f"          password: {q(env['WIFI_PASSWORD'])}",
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    out = Path(sys.argv[1])
    env = dict(os.environ)
    missing = [k for k in ("PI_USER", "PI_HOSTNAME", "PI_TIMEZONE", "PI_SSH_KEY") if not env.get(k)]
    if missing:
        raise SystemExit(f"missing environment: {', '.join(missing)}")
    if env.get("WIFI_SSID") and not env.get("WIFI_PASSWORD"):
        raise SystemExit("WIFI_PASSWORD is required with WIFI_SSID")
    out.mkdir(parents=True, exist_ok=True)
    (out / "user-data").write_text(user_data(env))
    (out / "network-config").write_text(network_config(env))
    (out / "meta-data").write_text(f"instance-id: iid-{env['PI_HOSTNAME']}\n")


if __name__ == "__main__":
    main()
